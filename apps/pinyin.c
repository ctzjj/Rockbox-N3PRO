char pinyin_first_letter(const char *utf8)
{
    unsigned char c = (unsigned char)utf8[0];
    unsigned int cp;
    if (c < 0xE0)
        return 0;
    cp = ((c & 0x0F) << 12) |
         (((unsigned char)utf8[1] & 0x3F) << 6) |
         ((unsigned char)utf8[2] & 0x3F);
    int lo = 0, hi = (int)(sizeof(py_table) / sizeof(py_table[0])) - 1;
    while (lo <= hi)
    {
        int mid = (lo + hi) / 2;
        if (py_table[mid].cp == cp)
            return (char)('A' + py_table[mid].letter - 1);
        if (py_table[mid].cp < cp)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return 0;
}
